
CREATE TABLE IF NOT EXISTS `HOST` (
    `IDX` BIGINT NOT NULL AUTO_INCREMENT,
    `NAME` VARCHAR(50) NOT NULL,
    `HOST` VARCHAR(50) NOT NULL,
    `TYPE` VARCHAR(10) NOT NULL,
    `TOPIC` VARCHAR(100) DEFAULT NULL,
    `HOST_ID` VARCHAR(30) DEFAULT NULL,
    `PASSWORD` VARCHAR(200) DEFAULT NULL,
    `CREATE_DT` DATETIME NOT NULL,
    `CREATE_AT` VARCHAR(100) NOT NULL,
    `UPDATE_DT` DATETIME NOT NULL,
    `UPDATE_AT` VARCHAR(100) NOT NULL,
    PRIMARY KEY (`IDX`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `FORMAT` (
    `IDX` BIGINT NOT NULL AUTO_INCREMENT,
    `NAME` VARCHAR(100) NOT NULL,
    `FORMAT` LONGTEXT NOT NULL,
    `CONTENT_TYPE` VARCHAR(50) DEFAULT NULL,
    `CREATE_DT` DATETIME NOT NULL,
    `UPDATE_DT` DATETIME NOT NULL,
    `CREATE_AT` VARCHAR(100) NOT NULL,
    `UPDATE_AT` VARCHAR(100) NOT NULL,
    PRIMARY KEY (`IDX`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `USERS` (
    `USERNAME` VARCHAR(100) NOT NULL,
    `PASSWORD` VARCHAR(255) NOT NULL,
    `CREATE_DT` DATETIME DEFAULT NULL,
    `UPDATE_DT` DATETIME DEFAULT NULL,
    `CREATE_AT` VARCHAR(100) DEFAULT NULL,
    `UPDATE_AT` VARCHAR(100) DEFAULT NULL,
    PRIMARY KEY (`USERNAME`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS `HISTORY` (
    `SN` BIGINT NOT NULL AUTO_INCREMENT,
    `USERNAME` VARCHAR(100) NOT NULL,
    `TITLE` VARCHAR(100) DEFAULT NULL,
    `DESCRIPTION` VARCHAR(1000) DEFAULT NULL,
    `FAVORITE_YN` BOOLEAN NOT NULL DEFAULT FALSE,
    `FAVORITE_DT` DATETIME DEFAULT NULL,
    `CREATE_DT` DATETIME NOT NULL,
    `PATH` LONGTEXT DEFAULT NULL,
    `TYPE` VARCHAR(20) DEFAULT NULL,
    `HOST` VARCHAR(255) DEFAULT NULL,
    `TOPIC` VARCHAR(255) DEFAULT NULL,
    `HOST_ID` VARCHAR(100) DEFAULT NULL,
    `HOST_PASSWORD` VARCHAR(255) DEFAULT NULL,
    `SPEED` DOUBLE DEFAULT NULL,
    `SPEED_UNIT` VARCHAR(20) DEFAULT NULL,
    `CYCLE` INT DEFAULT NULL,
    `FORMAT` LONGTEXT DEFAULT NULL,
    `PARAMETER` LONGTEXT DEFAULT NULL,
    PRIMARY KEY (`SN`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
